"""Write contracts/student-words.json from the word lists Part 5's own validators use (TICKET-049, AC-C16).

    uv run python scripts/make_student_words.py [--check] [--out FILE]        (`make student-words`)

Part 7's guard refuses the same lines Part 5 does, so it needs the same words. The file is generated, never
typed: `banned` is the word stems of `part5.opinion.guard.BANNED`, each written with a trailing `*` because Part 5
matches any word that starts with the stem (the convention of Part 7's guard), `praise` is
`part5.phrasing.template.PRAISE_PHRASES` and `ignored_characters` are the zero-width characters `template` reads
past. The lists are imported and read when `build` runs, so a change to a validator list changes the output, and
`tests/test_student_words.py` fails until the committed file is regenerated. A `BANNED` that is no longer a plain
alternation of word stems stops the script (exit 1) instead of writing a file that no longer says what the
validator does.

`--check` writes nothing and exits 1 when the file at `--out` (default `contracts/student-words.json`) differs.
Deterministic: the output depends only on the two lists.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from part5.opinion import guard      # noqa: E402
from part5.phrasing import template  # noqa: E402

OUT = ROOT / "contracts" / "student-words.json"
FORMAT = "simon.student-words.v1"
VERSION = "1.0.0"   # the layout of this file; a change to a list changes lists_sha256, which a reader compares
_ALTERNATION = re.compile(r"\\b\(\?:(.+)\)\\b")
_STEM = re.compile(r"[a-z]+\\w\*")
PREFIX = "*"   # a trailing * on a banned entry: any word that starts with the entry before it


MATCH = (
    "Compare case-insensitively, on the line lower-cased, word-bounded (\\b before and after). A banned entry that ends "
    "in * matches any word that starts with the entry before the *; an entry without * is a whole word (the "
    "validator has none today). A praise entry is a phrase of whole words, written with single spaces, that matches "
    "when its words are joined by any run of whitespace or hyphens (nice-effort, nice  effort). Zero-width "
    "characters (ignored_characters) are ignored: read the line twice, once with each one removed and once with "
    "each one replaced by a space, and refuse it when either reading matches. A fault line also has the typographic "
    "apostrophe read as a straight one before the test. A line that matches an entry is refused where applies_to says the list is tested.")


class WordsError(Exception):
    """A validator list is not in the shape this script knows how to write."""


def banned_entries(rx):
    """The entries of `rx`, a `\\b(?:stem\\w*|...)\\b` pattern, each `stem*` (a prefix match); WordsError when it has
    another shape."""
    found = _ALTERNATION.fullmatch(rx.pattern)
    terms = found.group(1).split("|") if found else []
    if not terms or not all(_STEM.fullmatch(t) for t in terms):
        raise WordsError(f"guard.BANNED is not \\b(?:stem\\w*|...)\\b any more: {rx.pattern!r}")
    stems = [t[:-len(r"\w*")] for t in terms]
    rebuilt = re.compile(r"\b(?:" + "|".join(s + r"\w*" for s in stems) + r")\b", rx.flags)
    if rebuilt.pattern != rx.pattern or not rx.flags & re.IGNORECASE:
        raise WordsError("guard.BANNED does not read as case-insensitive word stems")
    return [s + PREFIX for s in stems]


def ignored_characters(rx):
    """The zero-width characters of `rx`, a `[...]` class of single characters, as `U+XXXX` names."""
    body = rx.pattern
    if not (body.startswith("[") and body.endswith("]") and len(body) > 2):
        raise WordsError(f"template._ZERO_WIDTH is not a character class any more: {body!r}")
    return [f"U+{ord(c):04X}" for c in sorted(set(body[1:-1]))]


def build():
    """The document, as a dict."""
    banned = banned_entries(guard.BANNED)
    praise = list(template.PRAISE_PHRASES)
    ignored = ignored_characters(template._ZERO_WIDTH)
    lists = {"banned": banned, "praise": praise, "ignored_characters": ignored}
    digest = hashlib.sha256(json.dumps(lists, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return {
        "format": FORMAT,
        "version": VERSION,
        "description": (
            "The words Part 5's validators keep out of a line a student reads, for a reader that applies the same "
            "test without importing Part 5. Generated by scripts/make_student_words.py from the lists named in "
            "sources; never edit by hand."),
        "match": MATCH,
        "banned": banned,
        "praise": praise,
        "applies_to": {
            "banned": ("the notes and observations of the second opinion (part5/opinion/guard.py); "
                       "a fault line is not tested against it"),
            "praise": ("every fault line a model writes, timed or not, and the notes and observations of the "
                       "second opinion (part5/phrasing/template.py, part5/opinion/guard.py)"),
        },
        "ignored_characters": ignored,
        "sources": {
            "banned": "part5.opinion.guard.BANNED",
            "praise": "part5.phrasing.template.PRAISE_PHRASES",
            "ignored_characters": "part5.phrasing.template._ZERO_WIDTH",
        },
        "lists_sha256": digest,
    }


def render(doc):
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(prog="make_student_words", description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the file differs")
    ap.add_argument("--out", default=str(OUT), help="the file to write or check (default contracts/student-words.json)")
    args = ap.parse_args(argv)
    try:
        text = render(build())
    except WordsError as e:
        print(f"make_student_words: {e}", file=sys.stderr)
        return 1
    path = Path(args.out)
    if args.check:
        if not path.is_file() or path.read_text() != text:
            print(f"make_student_words: {path} differs from the validator's lists; run make student-words",
                  file=sys.stderr)
            return 1
        print(f"make_student_words: {path} is up to date")
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
