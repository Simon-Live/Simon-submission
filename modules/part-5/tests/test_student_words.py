# ---------------------------------------------------------------- a matcher built from the file agrees with the validator
def matchers(doc):
    """What a reader that never imports Part 5 builds from the file alone, following `match`: a trailing * on a banned
    entry is a prefix match, any other entry a whole word."""
    banned = re.compile(r"\b(?:" + "|".join(e[:-1] + r"\w*" if e.endswith("*") else e for e in doc["banned"]) + r")\b", re.I)
    hidden = [chr(int(c[2:], 16)) for c in doc["ignored_characters"]]
    phrase = re.compile(r"\b(?:" + "|".join(r"[\s\-]+".join(map(re.escape, p.split())) for p in doc["praise"]) + r")\b", re.I)

    def is_banned(text):
        return bool(banned.search(text.lower()))

    def is_praise(text):
        lowered = text.lower()
        removed, spaced = lowered, lowered
        for ch in hidden:
            removed, spaced = removed.replace(ch, ""), spaced.replace(ch, " ")
        return bool(phrase.search(removed) or phrase.search(spaced))
    return is_banned, is_praise


def variants(phrase):
    zw = "\N{ZERO WIDTH SPACE}"
    words = phrase.split()
    yield phrase
    yield phrase.upper()
    yield phrase.capitalize()
    yield f"Your knees are not bent enough at 1.4 s, {phrase}."
    yield "-".join(words)
    yield "  ".join(words)
    yield zw.join(phrase)                      # a zero-width character between every letter
    yield phrase.replace(" ", zw)              # a zero-width character as the only separator
    yield f"x{phrase}"                         # not whole words
    yield f"{phrase}s"
    yield phrase.replace(" ", "", 1) if len(words) > 1 else phrase + "x"


def test_the_matcher_from_the_file_agrees_with_the_validators_praise_test_on_every_phrase_variant():
    is_banned, is_praise = matchers(committed())
    lines = [v for p in template.PRAISE_PHRASES for v in variants(p)]
    lines += ["good form otherwise", "well aligned otherwise", "keep going", "almost there", "great depth", "no fault here"]
    assert any(template.praise(line.lower()) for line in lines) and not all(template.praise(line.lower()) for line in lines)
    for line in lines:
        assert is_praise(line) == bool(template.praise(line.lower())), repr(line)


def test_the_matcher_from_the_file_agrees_with_the_validators_banned_test_on_every_stem_variant():
    doc = committed()
    is_banned, _ = matchers(doc)
    lines = []
    for stem in (e[:-1] for e in doc["banned"]):
        lines += [stem, stem.upper(), stem + "ing", stem + "s", f"your {stem.capitalize()} is wide", f"un{stem}", f"{stem}-led",
                  f"a {stem[:-1]}", stem[1:]]
    lines += ["knees too far in", "a painted wall", "compare the trainers", "healthy", "patience", "coaching"]
    assert any(guard.BANNED.search(line.lower()) for line in lines) and not all(guard.BANNED.search(line.lower()) for line in lines)
    for line in lines:
        assert is_banned(line) == bool(guard.BANNED.search(line.lower())), repr(line)


def test_the_second_opinion_guard_refuses_a_line_for_each_listed_word_and_phrase():
    """The file's words are the ones that make `guard.text_problem` refuse a line, with the two reasons it gives."""
    doc = committed()
    shows = {"knee": {"left", "right"}}
    for stem in (e[:-1] for e in doc["banned"]):
        assert guard.text_problem(f"your {stem}ing knees look wide", 5.0, shows) == "uses a word this product does not use", stem
    for phrase in doc["praise"]:
        assert guard.text_problem(f"your knees look wide, {phrase}", 5.0, shows) == "adds praise", phrase
    assert guard.text_problem("your knees look wide", 5.0, shows) is None


def test_the_fault_line_test_refuses_a_listed_praise_phrase_and_does_not_read_the_banned_list():
    fault = {"measure": "knee_flexion", "side": "left", "direction": "less", "text": "left knee not bent enough",
             "text_timed": "left knee not bent enough at 1.4 s", "at_s": 1.4, "lateral": None}
    assert template.line_problem(fault, "Your left knee is not bent enough at 1.4 s.", timed=True) is None
    for phrase in committed()["praise"]:
        assert template.line_problem(fault, f"Your left knee is not bent enough at 1.4 s, {phrase}.", timed=True) == "adds praise", phrase
    assert template.line_problem(fault, "Your coach says the left knee is not bent enough at 1.4 s.", timed=True) is None


