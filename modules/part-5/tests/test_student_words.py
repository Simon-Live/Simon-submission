import json
import re
import unicodedata
from pathlib import Path

import pytest

from part5.opinion import guard
from part5.phrasing import template

ROOT = Path(__file__).resolve().parent.parent
FILE = ROOT / "contracts/student-words.json"
SCRIPT = ROOT / "scripts/make_student_words.py"
needs_workspace = pytest.mark.skipif(not (ROOT / ".simon-publish").is_file(),
                                     reason=".simon-publish is a workspace file, not part of the published repository")


def load_script():
    spec = importlib.util.spec_from_file_location("make_student_words", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gen = load_script()


def committed():
    return json.loads(FILE.read_text())


# ---------------------------------------------------------------- the file equals what the validator uses
def test_the_committed_file_equals_what_the_script_generates():
    assert FILE.read_text() == gen.render(gen.build())


def test_check_exits_0_on_the_committed_file_and_1_on_any_difference(tmp_path, capsys):
    assert gen.main(["--check"]) == 0
    stale = tmp_path / "student-words.json"
    stale.write_text(FILE.read_text().replace('"bravo"', '"bravo", "extra"'))
    assert gen.main(["--check", "--out", str(stale)]) == 1
    assert "differs from the validator's lists" in capsys.readouterr().err
    assert gen.main(["--check", "--out", str(tmp_path / "missing.json")]) == 1


def test_the_script_writes_the_same_bytes_to_another_path_and_twice(tmp_path):
    out = tmp_path / "words.json"
    assert gen.main(["--out", str(out)]) == 0
    first = out.read_bytes()
    assert first == FILE.read_bytes()
    assert gen.main(["--out", str(out)]) == 0 and out.read_bytes() == first


def test_the_lists_are_the_validators_constants_not_copies():
    doc = committed()
    assert doc["praise"] == list(template.PRAISE_PHRASES)
    assert all(entry.endswith("*") for entry in doc["banned"])
    rebuilt = re.compile(r"\b(?:" + "|".join(entry[:-1] + r"\w*" for entry in doc["banned"]) + r")\b", guard.BANNED.flags)
    assert rebuilt.pattern == guard.BANNED.pattern and rebuilt.flags == guard.BANNED.flags
    assert "".join(chr(int(c[2:], 16)) for c in doc["ignored_characters"]) == "".join(sorted(template._ZERO_WIDTH.pattern[1:-1]))
    assert doc["lists_sha256"] == hashlib.sha256(json.dumps(
        {"banned": doc["banned"], "praise": doc["praise"], "ignored_characters": doc["ignored_characters"]},
        sort_keys=True, separators=(",", ":")).encode()).hexdigest()


@pytest.mark.parametrize("module,name,value", [
    (template, "PRAISE_PHRASES", template.PRAISE_PHRASES + ("top marks",)),
    (guard, "BANNED", re.compile(guard.BANNED.pattern.replace(r"health\w*", r"wellbeing\w*|health\w*"), guard.BANNED.flags)),
])
def test_a_change_to_a_validator_list_changes_the_generated_file(monkeypatch, module, name, value):
    monkeypatch.setattr(module, name, value)
    assert gen.render(gen.build()) != FILE.read_text()


@pytest.mark.parametrize("pattern", [r"\bcoach\w*\b", r"\b(?:coach\w*|re-hab\w*)\b", r"(?:coach\w*|rehab\w*)", r"coach|rehab"])
def test_a_banned_pattern_that_is_not_plain_stems_stops_the_script(monkeypatch, pattern, capsys):
    monkeypatch.setattr(guard, "BANNED", re.compile(pattern, re.I))
    assert gen.main(["--check"]) == 1
    assert "guard.BANNED" in capsys.readouterr().err


def test_a_banned_pattern_that_is_case_sensitive_stops_the_script(monkeypatch):
    monkeypatch.setattr(guard, "BANNED", re.compile(guard.BANNED.pattern))
    with pytest.raises(gen.WordsError):
        gen.build()


