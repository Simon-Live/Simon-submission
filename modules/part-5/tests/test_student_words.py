"""contracts/student-words.json (docs/specs/integration-contract.md AC-C16, TICKET-049, Part 7 TICKET-183): the banned word
stems and the praise phrases Part 5's validators use, generated by scripts/make_student_words.py from the validators' own
constants. The committed file must equal what the script generates, so it cannot drift from the validator, and a matcher
built from the file alone must agree with the validator on a set of lines."""
import hashlib
